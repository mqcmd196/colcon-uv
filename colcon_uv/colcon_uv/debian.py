"""Bundle Python packages in bloom-generated Debian packages."""

import argparse
import re
import shlex
import shutil
import subprocess
from pathlib import Path

from catkin_pkg.package import parse_package

from colcon_uv.build_type import PYTHON
from colcon_uv.dependencies.install import UvPackage, install_dependencies


def _project(path):
    project = UvPackage(Path(path).resolve())
    manifest = parse_package(str(project.path / "package.xml"))
    if project.build_type != PYTHON or manifest.get_build_type() != "ament_python":
        raise ValueError("Debian bundling only supports Python/ament_python packages")
    config = project.pyproject_data["tool"]["colcon-uv-ros"]
    if config.get("extra-site-packages"):
        raise ValueError(
            "extra-site-packages cannot be bundled; declare wheel dependencies instead"
        )
    return project, manifest


def prepare_debian(path):
    """Replace bloom's rules with a local venv-bundling build."""
    project, manifest = _project(path)
    debian = project.path / "debian"
    control = (debian / "control").read_text()
    packages = re.findall(r"^Package: ([a-z0-9][a-z0-9+.-]*)$", control, re.MULTILINE)
    if len(packages) != 1 or not packages[0].endswith(
        "-" + manifest.name.replace("_", "-")
    ):
        raise ValueError(
            "Expected bloom control for this package with one binary package"
        )
    rules_path = debian / "rules"
    original = rules_path.read_text()
    prefix = re.search(r'--prefix "(/[^"\s]+)"', original)
    if not prefix:
        raise ValueError(
            "Run bloom-generate rosdebian first (expected its --prefix setting)"
        )
    prefix = prefix.group(1)
    if not re.fullmatch(r"/[a-zA-Z0-9_/-]+", prefix):
        raise ValueError("Unsupported installation prefix")
    package = packages[0]
    # Preserve bloom's dependency declarations and keep native wheels architecture-specific.
    control = re.sub(
        r"^Architecture:.*$", "Architecture: any", control, flags=re.MULTILINE
    )
    if "${python3:Depends}" not in control:
        raise ValueError(
            "Expected bloom's Python dependency substitution in debian/control"
        )
    rules = f"""#!/usr/bin/make -f
# Generated by colcon uv prepare-debian. Re-run after bloom-generate.
COLCON_UV_PYTHON ?= /usr/bin/python3

%:
\tdh $@ --with python3

override_dh_auto_clean:
\trm -rf .colcon-uv-debian .colcon-uv-python-depends

override_dh_auto_configure:

override_dh_auto_build:
\t$(COLCON_UV_PYTHON) -m colcon_uv.debian build --output .colcon-uv-debian

override_dh_auto_test:
\t# Run project tests separately before packaging.

override_dh_auto_install:
\tmkdir -p debian/{package}{prefix}
\tcp -a .colcon-uv-debian/. debian/{package}{prefix}/

# Preserve uv's relocatable scripts and bundled wheel binaries.
override_dh_python3:
override_dh_strip:
override_dh_shlibdeps:

override_dh_gencontrol:
\tdh_gencontrol -- "-Vpython3:Depends=$$(cat .colcon-uv-python-depends)"
"""
    (debian / "control").write_text(control)
    rules_path.write_text(rules)
    rules_path.chmod(0o755)


def _relative_path(value):
    path = Path(value)
    if path.is_absolute() or ".." in path.parts:
        raise ValueError(f"Expected a path inside the package: {value}")
    return path


def build_bundle(path, output):
    """Build a source-independent install tree for Debian staging."""
    project, manifest = _project(path)
    output = Path(output).resolve()
    if output.exists():
        raise ValueError(
            f"Output already exists; remove it before rebuilding: {output}"
        )
    config = project.pyproject_data["tool"]["colcon-uv-ros"]
    data_files = config.get("data-files", {})
    for destination, sources in data_files.items():
        _relative_path(destination)
        if not isinstance(sources, list):
            raise ValueError(f"data-files.{destination} must be an array")
        for source in sources:
            source_path = project.path / _relative_path(source)
            if not source_path.exists():
                raise ValueError(f"Missing data file: {source_path}")
    scripts = project.pyproject_data.get("project", {}).get("scripts", {})
    for script in scripts:
        if not re.fullmatch(r"[a-zA-Z0-9_.-]+", script) or script in (
            ".",
            "..",
            "venv",
        ):
            raise ValueError(f"Unsupported console script name: {script}")
    lib_dir = output / "lib" / manifest.name
    venv_base = output / "lib/colcon_uv" / manifest.name
    venv = install_dependencies(project, venv_base, True, bundle=True)
    for destination, sources in data_files.items():
        dest = output / destination
        dest.mkdir(parents=True, exist_ok=True)
        for source in sources:
            source_path = project.path / source
            target = dest / source_path.name
            if source_path.is_dir():
                shutil.copytree(source_path, target, dirs_exist_ok=True)
            else:
                shutil.copy2(source_path, target)
    share = output / "share" / manifest.name
    share.mkdir(parents=True, exist_ok=True)
    shutil.copy2(project.path / "package.xml", share / "package.xml")
    marker = output / "share/ament_index/resource_index/packages" / manifest.name
    marker.parent.mkdir(parents=True, exist_ok=True)
    marker.touch()
    lib_dir.mkdir(parents=True, exist_ok=True)
    for script in scripts:
        if not (venv / "bin" / script).is_file():
            raise ValueError(f"Console script was not installed: {script}")
        wrapper = lib_dir / script
        wrapper.write_text(
            "#!/bin/sh\n"
            'script_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)\n'
            f'exec "$script_dir/../colcon_uv/{manifest.name}/venv/bin/"'
            f'{shlex.quote(script)} "$@"\n'
        )
        wrapper.chmod(0o755)
    # Match the interpreter ABI used by the bundled wheels, not the build frontend.
    version = subprocess.check_output(
        ["/usr/bin/python3", "-c", "import sys; print('%d.%d' % sys.version_info[:2])"],
        text=True,
    ).strip()
    major, minor = map(int, version.split("."))
    (project.path / ".colcon-uv-python-depends").write_text(
        f"python3 (>= {major}.{minor}), python3 (<< {major}.{minor + 1})\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest="command", required=True)
    prepare = subparsers.add_parser("prepare")
    prepare.add_argument("path", nargs="?", default=".")
    build = subparsers.add_parser("build")
    build.add_argument("--output", required=True)
    args = parser.parse_args()
    if args.command == "prepare":
        prepare_debian(args.path)
    else:
        build_bundle(Path.cwd(), args.output)


if __name__ == "__main__":
    main()
